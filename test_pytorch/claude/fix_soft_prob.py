    "\n",
    "# Diagnostic: check key crisis events\n",
    'print("\\n=== Crisis Event Coverage ===")\n',
    'events = [("COVID", "2020-03-01", "2020-08-31"),\n',
    '          ("Russia-Ukraine", "2022-02-01", "2022-06-30"),\n',
    '          ("Israel-Hamas", "2023-10-01", "2024-01-31")]\n',
    "for name, start, end in events:\n",
    "    mask = (df_kf['observation_date'] >= start) & (df_kf['observation_date'] <= end)\n",
    "    if mask.any():\n",
    "        regime_counts = df_kf.loc[mask, 'regime_label'].value_counts().sort_index()\n",
    "        total = mask.sum()\n",
    '        print(f"  {name} ({start} to {end}): n={total}")\n',
    "        for r, c in regime_counts.items():\n",
