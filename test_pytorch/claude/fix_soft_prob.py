    "def causal_majority_vote(regimes, window=21):\n",
    '    """Rolling mode using only past data (causal, no look-ahead)."""\n',
    "    result = np.zeros_like(regimes)\n",
    "    for t in range(len(regimes)):\n",
    "        start = max(0, t - window + 1)\n",
    "        window_data = regimes[start:t+1]\n",
    "        values, counts = np.unique(window_data, return_counts=True)\n",
    "        result[t] = values[np.argmax(counts)]\n",
    "    return result\n",
    "\n",
    "smoothed_regime = causal_majority_vote(raw_regime_semantic, window=21)\n",
    "df_kf['regime_label'] = smoothed_regime.astype(int)\n",
    "\n",
    "# Store soft probabilities in df_kf\n",
    "for k in range(n_regimes):\n",
    "    df_kf[f'regime_prob_{k}'] = proba_semantic[:, k]\n",
    "\n",
    'print(f"\\nRegime distribution (after causal smoothing):")\n',
