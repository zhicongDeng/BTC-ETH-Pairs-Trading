    "raw_labels = gmm_selected.predict(state_data)\n",
    "means = gmm_selected.means_.flatten()\n",
    "order = np.argsort(means)\n",
    "label_map = {order[i]: i for i in range(n_regimes)}\n",
    "raw_regime = np.array([label_map[l] for l in raw_labels])\n",
    "\n",
    "# --- Soft probabilities (posterior responsibilities) ---\n",
    "raw_proba = gmm_selected.predict_proba(state_data)  # shape (T, n_regimes)\n",
    "# Reorder columns to match distance-ordering\n",
    "proba_reordered = raw_proba[:, order]\n",
    "\n",
    "# Fix label semantics: ensure higher regime number = higher OVX\n",
    "mean_ovx_by_regime = {}\n",
    "for r in range(n_regimes):\n",
    "    mask = raw_regime == r\n",
    "    if mask.any():\n",
    "        mean_ovx_by_regime[r] = df_kf.loc[df_kf.index[mask], 'OVX_Close'].mean()\n",
    "\n",
    "regime_order_by_ovx = sorted(mean_ovx_by_regime, key=mean_ovx_by_regime.get)\n",
    "semantic_map = {regime_order_by_ovx[i]: i for i in range(n_regimes)}\n",
    "raw_regime_semantic = np.array([semantic_map[r] for r in raw_regime])\n",
    "\n",
    "# Apply same semantic remapping to probability columns\n",
    "proba_semantic = np.zeros_like(proba_reordered)\n",
    "for old_r, new_r in semantic_map.items():\n",
    "    proba_semantic[:, new_r] = proba_reordered[:, old_r]\n",
